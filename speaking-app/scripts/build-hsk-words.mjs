/**
 * Regenerates lib/hsk-words.js: the official HSK level 1-2 word lists with
 * every pinyin reading of each word, from drkameleon/complete-hsk-vocabulary
 * (MIT). The plan's own pinyin is checked against these readings in tests.
 *
 *   HSK 2.0 levels 1-2  the lists HSK Standard Course 1 and 2 are built on
 *   HSK 3.0 levels 1-2  the newer national standard (GF 0025-2021)
 *
 * Usage: node scripts/build-hsk-words.mjs
 */
import fs from 'node:fs/promises';

const BASE = 'https://raw.githubusercontent.com/drkameleon/complete-hsk-vocabulary/main/wordlists/exclusive';
const LISTS = [
  ['old/1', 'hsk2-1'],
  ['old/2', 'hsk2-2'],
  ['new/1', 'hsk3-1'],
  ['new/2', 'hsk3-2'],
];

const words = new Map();
for (const [path, tag] of LISTS) {
  const res = await fetch(`${BASE}/${path}.json`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  for (const w of await res.json()) {
    const entry = words.get(w.simplified) || { readings: new Set(), lists: [] };
    for (const form of w.forms) entry.readings.add(form.transcriptions.pinyin.toLowerCase());
    entry.lists.push(tag);
    words.set(w.simplified, entry);
  }
}

const rows = [...words].map(([hanzi, e]) => `  ${JSON.stringify(hanzi)}: [${JSON.stringify([...e.readings].join('|'))}, ${JSON.stringify(e.lists.join(' '))}],`);
const out = `// Generated by scripts/build-hsk-words.mjs. Do not edit by hand.
// Source: https://github.com/drkameleon/complete-hsk-vocabulary (MIT License).
// hanzi: [readings separated by |, lists] where lists holds hsk2-1, hsk2-2, hsk3-1, hsk3-2.

export const HSK_WORDS = Object.freeze({
${rows.join('\n')}
});
`;
await fs.writeFile(new URL('../lib/hsk-words.js', import.meta.url), out);
console.log(`wrote ${words.size} words`);
